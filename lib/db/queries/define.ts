import type { PgDatabase } from "drizzle-orm/pg-core";
import type { PostgresJsQueryResultHKT } from "drizzle-orm/postgres-js";
import type * as schema from "../schema";

/**
 * The query registry (ADR 0005).
 *
 * Every query the app runs is defined once with `defineQuery`, in a file under lib/db/queries/,
 * and listed in lib/db/queries/index.ts. `pnpm db:queries` writes each one's SQL to
 * db/queries/<name>.sql, and `queries.test.ts` fails if a committed file is out of date.
 *
 * This file has no database connection, so the snapshot script and tests can import it.
 * Running a query goes through lib/db/queries/run.ts (server only).
 */

/** The database or a transaction: both can run any query. */
export type Executor = PgDatabase<PostgresJsQueryResultHKT, typeof schema>;

interface SqlText {
  sql: string;
  params: unknown[];
}

/** A Drizzle query builder (has toSQL) or a raw `db.execute(sql…)` (has getQuery). */
export type Buildable<R> = PromiseLike<R> & ({ toSQL(): SqlText } | { getQuery(): SqlText });

export interface Query<A, R> {
  /** "<area>/<name>", also the path of its snapshot: db/queries/<area>/<name>.sql */
  name: string;
  /** One or two sentences: what it is for and who calls it. */
  description: string;
  /** Example arguments, used only to render the snapshot. Must be invented data. */
  example: A;
  build(db: Executor, args: A): Buildable<R>;
}

/** Any registered query, whatever its arguments and result (for lists of queries). */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type AnyQuery = Query<any, unknown>;

export function defineQuery<A, R>(q: Query<A, R>): Query<A, R> {
  if (!/^[a-z0-9-]+\/[a-z0-9-]+$/.test(q.name)) {
    throw new Error(`Query name "${q.name}" must look like "area/name" (lowercase, digits, dashes)`);
  }
  return q;
}

function sqlOf(built: Buildable<unknown>): SqlText {
  return "toSQL" in built ? built.toSQL() : built.getQuery();
}

const BREAK_BEFORE = [
  "from", "where", "and", "or", "group by", "having", "order by", "limit", "offset",
  "left join", "inner join", "values", "returning", "on conflict", "do update set", "set",
];

/** Removes the indentation shared by all non-empty lines, and blank lines at either end. */
function dedent(sql: string): string {
  const lines = sql.replace(/^\s*\n|\n\s*$/g, "").split("\n");
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)![0].length));
  return lines.map((l) => l.slice(indent).trimEnd()).join("\n");
}

/**
 * Makes SQL readable in diffs without changing what it means.
 * - SQL written by hand across several lines (raw `sql` templates) keeps its layout, dedented.
 * - Drizzle's one-line SQL gets each main clause on its own line, splitting only outside quotes
 *   ('…' literals and "…" identifiers).
 */
export function formatSql(sql: string): string {
  if (sql.includes("\n")) return dedent(sql);
  let out = "";
  let quote: string | null = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote) {
      out += ch;
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
      continue;
    }
    if (ch === " ") {
      const rest = sql.slice(i + 1).toLowerCase();
      const kw = BREAK_BEFORE.find((k) => rest.startsWith(`${k} `) || rest.startsWith(`${k}(`));
      if (kw) {
        out += "\n" + (kw === "and" || kw === "or" ? "  " : "");
        continue;
      }
    }
    out += ch;
  }
  return out;
}

/** The text of db/queries/<name>.sql for a query. `db` is a mock client: nothing connects. */
export function renderSnapshot(q: AnyQuery, db: Executor, file: string): string {
  const { sql, params } = sqlOf(q.build(db, q.example));
  const paramLines = params.map((p, i) => `--   $${i + 1} = ${JSON.stringify(p)}`);
  return [
    `-- ${q.name}`,
    ...q.description.split("\n").map((l) => `-- ${l}`.trimEnd()),
    "--",
    params.length ? "-- Parameters, with the example values used to render this file:" : "-- No parameters.",
    ...paramLines,
    "--",
    `-- Generated by \`pnpm db:queries\` from ${file}. Do not edit by hand.`,
    "",
    `${formatSql(sql)};`,
    "",
  ].join("\n");
}
